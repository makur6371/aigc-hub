/**
 * 按当前所在工具推断「应当默认带上的技能」。
 *
 * 场景：用户从「俄区智能套图」工具切到智能体模式，他显然是要做俄区套图 ——
 * 却要自己再去技能列表里找一次，属于让用户重复表达已经用工具名说过的意图。
 * 工具 slug 形如 `俄区智能套图-seed206`，按关键词匹配即可（顺序即优先级）。
 *
 * 只做「默认值」，永不覆盖用户的手动选择（调用方负责只在空选时填充）。
 */
export function skillForToolSlug(slug: string | null | undefined): string | null {
  if (!slug) return null
  if (slug.includes('拼多多')) return 'pdd-suite'
  // 只给「电商视频」类工具默认带展示视频技能。
  // 基础·文生视频 / 图生视频 / 首尾帧生视频不是电商场景，不能一律套这个 Skill。
  if (slug.includes('电商') && slug.includes('视频')) return 'ecom-showcase-video'
  if (slug.includes('九宫格')) return 'nine-grid'
  if (slug.includes('俄区')) return 'ru-market'
  if (slug.includes('模特换背景')) return 'model-bg'
  if (slug.includes('电商图替换')) return 'ecom-scene'
  if (slug.includes('套图')) return 'ecom-main'
  if (slug.includes('放大')) return 'upscale'
  if (slug.includes('图生图')) return 'ecom-scene'
  return null
}

export function getAgentSkills(ids: unknown): AgentSkill[] {
  if (!Array.isArray(ids)) return []
  const seen = new Set<string>()
  const out: AgentSkill[] = []
  for (const id of ids) {
    if (typeof id !== 'string') continue
    const skill = AGENT_SKILLS.find((s) => s.id === id)
    if (skill && !seen.has(skill.id)) { seen.add(skill.id); out.push(skill) }
  }
  return out
}

/** 把选中的 skill fragments 追加到 planner system prompt 尾部（用户明确指定优先于 Skill 默认值） */
export function appendSkillFragments(basePrompt: string, skills: AgentSkill[]): string {
  if (skills.length === 0) return basePrompt
  const block = skills.map((s) => `\n【Skill: ${s.name}】\n${s.promptFragment}`).join('\n')
  return `${basePrompt}\n\n以下为用户启用的 Skill 领域规范，仅在用户未明确指定相关项时提供默认值；用户明确指定的数量、比例、风格、模型、内容范围永远优先于 Skill 规范：${block}\n`
}
