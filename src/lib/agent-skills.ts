// Agent Skills（Claude Code 风格）：领域知识 + 约束打包为可插拔 prompt 模块
//
// ===== 结构约定（以 ru-market「俄区套图」为模板）=====
// 一个成熟 skill 的 promptFragment 应当包含这 4 段，缺一段就会出现「模型乱来」：
//   1. 用法/方向   —— 这个领域要做哪几类图/产出，从哪些维度拆分
//   2. 说明        —— 整体风格、受众、平台特点（一两句，不啰嗦）
//   3. 约束        —— 必须遵守的硬规则（参考图怎么传、文案语言、禁止项、信息不全先问）
//   4. 二次修改    —— 用户指着某张已生成的图说「这里改一下」时怎么处理（原位编辑）
//
// 反面教材：早期的 ecom-main 只有「白底、文字不超 8 字」两句，模型收到「做套图」时
// 完全不知道该出哪几个方向、参考图传不传、文案用什么语言 —— 于是东一张西一张。
// ru-market 之所以稳，就是因为这 4 段都写全了。

export type AgentSkillGroup = '电商视频' | '电商套图' | '图片处理' | '内容与分镜' | '手绘插画'

/** 展示顺序（与选择器一致，避免靠对象顺序隐式决定 UI） */
export const AGENT_SKILL_GROUPS: AgentSkillGroup[] = ['电商视频', '电商套图', '手绘插画', '图片处理', '内容与分镜']

export interface AgentSkill {
  id: string
  name: string
  icon: string
  /** 分组：技能选择器按此归类展示 */
  group: AgentSkillGroup
  description: string
  /** 注入 planner system prompt 尾部的领域片段 */
  promptFragment: string
}

/**
 * 通用「二次修改」段落：所有 skill 共用同一段处理方式，避免各写各的、口径漂移。
 * 关键词：原位编辑 —— 保留原图背景/构图/光线/文字，只改用户指出的那一处。
 */
const REWRITE_RULE = `
【二次修改：以原图为底图】
用户指着某张已生成的图说「这里不对，改成 X」时，要把那张图（素材N）作为参考图，
并把提示词写成**对它的原位编辑**：保留原有背景、构图、光线、色调与已排好的文字，
只改用户指出的那一处。不要把整张图重新描述一遍 —— 那等于让模型重画，
原有的背景与文案会一起丢掉。`

/**
 * 视频版「二次修改」：视频没有「原位编辑」，改的粒度是**单个镜头**。
 * 只重发被点名的那一条 generate_video，其它镜头保持不动；否则用户改一个镜头
 * 会把整条片子的结构、时长与已生成结果一起推翻。
 */
const VIDEO_REWRITE_RULE = `
【二次修改：只重发被点名的镜头】
用户说「第 2 个镜头换成俯拍」「镜头 1 推得太快」「最后一段重做」时：
- 只对那一个镜头重新调用 generate_video，其它镜头的提示词、时长、比例保持原样；
- 新提示词写清「保留什么、只改什么」（保留商品与首帧、只改机位速度/光线方向/动作幅度）；
- 不要把整条视频重新规划一遍，也不要顺手改动用户没有点名的镜头。`

/** 通用「信息不全先追问」段落 */
const ASK_FIRST_RULE = `信息不齐（生图模型/比例/档位/张数/文案语言）时先追问补齐，齐全后再发起生图；不要自行假设默认值。`

